import os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
# Generates the tensor-core GEMM kernel (literal PTX strings per accumulator tile).
lines = []
A = lines.append
A('using ILGPU;')
A('using ILGPU.Runtime;')
A('using ILGPU.Runtime.Cuda;')
A('using Half = ILGPU.Half;')
A('')
A('namespace LammaNet.Gpu;')
A('')
A('// <auto-generated> by tools/gpu-codegen/tensor_core_gemm.py: the PTX mma/mov strings name fixed accumulator registers,')
A('// so each of the warp\'s 8 (16x8) tiles has its own literal statements.')
A('')
A('internal static partial class Kernels')
A('{')
A('    public const int TcBM = 64, TcBN = 64, TcBK = 32, TcThreads = 128;')
A('    private const int TcLd = TcBK + 8; // padded shared row (halves): conflict-free fragment loads')
A('')
A('    /// <summary>')
A('    /// Tensor-core GEMM for prompt processing (sm_80+): mma.sync m16n8k16 with fp16 operands and fp32 accumulation.')
A('    /// A 128-thread block computes 64 weight rows x 64 tokens; weights are dequantized to fp16 and activations')
A('    /// converted to fp16 (clamped to its range) into k-contiguous shared tiles; warp w owns rows 32*(w/2).. and tokens')
A('    /// 32*(w%2).. as 2x4 mma tiles whose accumulators live in named PTX registers across the K loop.')
A('    /// </summary>')
A('    public static void TcGemm<T>(ArrayView<uint> w, ArrayView<float> f, ArrayView<float> x, ArrayView<float> y, GemmParams p)')
A('        where T : struct, IWeightFormat')
A('    {')
A('        var a16 = SharedMemory.Allocate<Half>(TcBM * TcLd);')
A('        var b16 = SharedMemory.Allocate<Half>(TcBN * TcLd);')
A('        var a32 = a16.Cast<uint>();')
A('        var b32 = b16.Cast<uint>();')
A('        var x4 = x.Cast<Float4>();')
A('        var fmt = default(T);')
A('        int tid = Group.IdxX, lane = tid & 31, warp = tid >> 5;')
A('        int tilesM = (p.Rows + TcBM - 1) / TcBM;')
A('        int row0 = (Grid.IdxX % tilesM) * TcBM, tok0 = (Grid.IdxX / tilesM) * TcBN;')
A('        int wr = (warp >> 1) * 32, wc = (warp & 1) * 32;')
A('        int g = lane >> 2, t4 = lane & 3;')
decl = '.reg .f32 tc<32>;' + ''.join(f'\\n\\tmov.f32 tc{i}, 0f00000000;' for i in range(32))
A(f'        CudaAsm.Emit("{decl}");')
A('        for (int k0 = 0; k0 < p.Cols; k0 += TcBK)')
A('        {')
A('            // weights: 64 rows x 4 groups of 8 columns -> 2 groups per thread')
A('            for (int e = 0; e < 2; e++)')
A('            {')
A('                int idx = tid + e * TcThreads, r = idx >> 2, kq = (idx & 3) * 8;')
A('                Float8 v = row0 + r < p.Rows ? fmt.Dequant8(w, p.WWord + (long)(row0 + r) * p.RowWords, p.Cols, k0 + kq) : default;')
A('                int o = r * TcLd + kq;')
A('                a16[o] = (Half)v.W0; a16[o + 1] = (Half)v.W1; a16[o + 2] = (Half)v.W2; a16[o + 3] = (Half)v.W3;')
A('                a16[o + 4] = (Half)v.W4; a16[o + 5] = (Half)v.W5; a16[o + 6] = (Half)v.W6; a16[o + 7] = (Half)v.W7;')
A('            }')
A('            // activations: 64 tokens x 8 float4 -> 4 per thread')
A('            for (int e = 0; e < 4; e++)')
A('            {')
A('                int idx = tid + e * TcThreads, t = idx >> 3, q = idx & 7;')
A('                Float4 xv = default;')
A('                if (tok0 + t < p.NTok) xv = x4[(p.XOff + (long)(tok0 + t) * p.XStride + k0) / 4 + q];')
A('                int o = t * TcLd + q * 4;')
A('                b16[o] = (Half)Clamp16(xv.X); b16[o + 1] = (Half)Clamp16(xv.Y); b16[o + 2] = (Half)Clamp16(xv.Z); b16[o + 3] = (Half)Clamp16(xv.W);')
A('            }')
A('            Group.Barrier();')
A('            for (int ks = 0; ks < TcBK; ks += 16)')
A('            {')
A('                int ka = (ks + 2 * t4) / 2; // word offset of k pair')
for mi in range(2):
    A(f'                int ra{mi} = (wr + {mi * 16} + g) * (TcLd / 2) + ka;')
    A(f'                uint a{mi}0 = a32[ra{mi}], a{mi}1 = a32[ra{mi} + 4 * TcLd], a{mi}2 = a32[ra{mi} + 4], a{mi}3 = a32[ra{mi} + 4 * TcLd + 4];')
for ni in range(4):
    A(f'                int rb{ni} = (wc + {ni * 8} + g) * (TcLd / 2) + ka;')
    A(f'                uint b{ni}0 = b32[rb{ni}], b{ni}1 = b32[rb{ni} + 4];')
for mi in range(2):
    for ni in range(4):
        base = 4 * (mi * 4 + ni)
        acc = ','.join(f'tc{base + i}' for i in range(4))
        A(f'                CudaAsm.Emit("mma.sync.aligned.m16n8k16.row.col.f32.f16.f16.f32 {{{acc}}}, {{%0,%1,%2,%3}}, {{%4,%5}}, {{{acc}}};", a{mi}0, a{mi}1, a{mi}2, a{mi}3, b{ni}0, b{ni}1);')
A('            }')
A('            Group.Barrier();')
A('        }')
# epilogue
for mi in range(2):
    for ni in range(4):
        base = 4 * (mi * 4 + ni)
        A(f'        {{')
        for i in range(4):
            A(f'            CudaAsm.Emit("mov.f32 %0, tc{base + i};", out float c{i});')
        A(f'            int r = row0 + wr + {mi * 16} + g, t = tok0 + wc + {ni * 8} + 2 * t4;')
        A(f'            TcStore(f, y, p, r, t, c0, c1);')
        A(f'            TcStore(f, y, p, r + 8, t, c2, c3);')
        A(f'        }}')
A('    }')
A('')
A('    private static float Clamp16(float v) => MathF.Max(-65504f, MathF.Min(65504f, v));')
A('')
A('    /// <summary>Stores the results of one weight row for two consecutive tokens.</summary>')
A('    private static void TcStore(ArrayView<float> f, ArrayView<float> y, GemmParams p, int r, int t, float v0, float v1)')
A('    {')
A('        if (r >= p.Rows) return;')
A('        float bias = p.BiasOff >= 0 ? f[p.BiasOff + r] : 0f;')
A('        GemmStore1(y, p, r, t, (v0 + bias) * p.Scale);')
A('        GemmStore1(y, p, r, t + 1, (v1 + bias) * p.Scale);')
A('    }')
A('}')
open(os.path.join(ROOT, 'src', 'Lamma.Net.Gpu', 'TensorCoreGemm.cs'), 'w', encoding='utf-8', newline='\r\n').write('\n'.join(lines) + '\n')
print('generated', len(lines), 'lines')
