import os
import sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
# Generates the pipelined tensor-core GEMM (TcGemm2). Usage: python tensor_core_gemm2.py [out.cs]
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'src', 'Lamma.Net.Gpu', 'TensorCoreGemm2.cs')

BM, BN, BK = (int(v) for v in os.environ.get("TC2_TILE", "64,128,32").split(","))
WM, WN = (int(v) for v in os.environ.get("TC2_WARPS", "2,4").split(","))  # warp grid: WM along weight rows, WN along tokens
THREADS = 32 * WM * WN
WTM, WTN = BM // WM, BN // WN  # warp tile (rows x tokens)
MT, NT = WTM // 16, WTN // 8   # mma tiles per warp
LD = BK + 8                    # padded shared row (halves): conflict-free fragment loads, 16-byte aligned rows
A_TOTAL, B_TOTAL = BM * BK // 8, BN * BK // 8          # 8-wide weight / activation groups per k-step
A_GROUPS = -(-A_TOTAL // THREADS)                      # per thread (the last one may be partial: guarded)
B_GROUPS = -(-B_TOTAL // THREADS)
assert A_TOTAL % THREADS == 0 or A_GROUPS == 1, 'partial weight groups only as a single guarded group'
assert B_TOTAL % THREADS == 0 or B_GROUPS == 1, 'partial activation groups only as a single guarded group'
A_GUARD = '' if A_TOTAL % THREADS == 0 else f'tid < {A_TOTAL} && '
B_GUARD = '' if B_TOTAL % THREADS == 0 else f'tid < {B_TOTAL} && '
NACC = 4 * MT * NT

L = []
A = L.append
A('using ILGPU;')
A('using ILGPU.Runtime;')
A('using ILGPU.Runtime.Cuda;')
A('using Half = ILGPU.Half;')
A('')
A('namespace LammaNet.Gpu;')
A('')
A('// <auto-generated> by tools/gpu-codegen/tensor_core_gemm2.py: the PTX mma/mov strings name fixed accumulator registers,')
A(f'// so each of the warp\'s {MT * NT} (16x8) tiles has its own literal statements.')
A('')
A('/// <summary>Four 32-bit words moved as one 16-byte vector.</summary>')
A('public struct Words4 { public uint A, B, C, D; }')
A('')
A('internal static partial class Kernels')
A('{')
A(f'    public const int Tc2BM = {BM}, Tc2BN = {BN}, Tc2BK = {BK}, Tc2Threads = {THREADS};')
A(f'    private const int Tc2Ld = {LD};')
A('')
A('    /// <summary>')
A('    /// Pipelined tensor-core GEMM for prompt processing (sm_80+): mma.sync m16n8k16 with fp16 operands and fp32')
A(f'    /// accumulation. A {THREADS}-thread block computes {BM} weight rows x {BN} tokens; warp w owns {WTM} rows x {WTN} tokens')
A(f'    /// ({MT}x{NT} mma tiles, accumulators in named PTX registers). Shared tiles are double-buffered: each k-step first')
A('    /// issues the next step\'s global loads (weights dequantized to fp16 pairs, activations already fp16 — see')
A('    /// <see cref="ToHalfRows"/>), then runs the mma on the current buffer, then stores the next step; one barrier per step.')
A('    /// </summary>')
A('    public static void TcGemm2<T>(ArrayView<uint> w, ArrayView<float> f, ArrayView<Half> xh, ArrayView<float> y, GemmParams p)')
A('        where T : struct, IWeightFormat')
A('    {')
A(f'        var a32 = SharedMemory.Allocate<uint>(2 * {BM} * ({LD} / 2));')
A(f'        var b32 = SharedMemory.Allocate<uint>(2 * {BN} * ({LD} / 2));')
A('        var a4 = a32.Cast<Words4>();')
A('        var b4 = b32.Cast<Words4>();')
A('        var x4 = xh.Cast<Words4>();')
A('        var fmt = default(T);')
A('        int tid = Group.IdxX, lane = tid & 31, warp = tid >> 5;')
A(f'        int tilesM = (p.Rows + {BM} - 1) / {BM};')
A(f'        int row0 = (Grid.IdxX % tilesM) * {BM}, tok0 = (Grid.IdxX / tilesM) * {BN};')
A(f'        int wr = (warp / {WN}) * {WTM}, wc = (warp % {WN}) * {WTN};')
A('        int g = lane >> 2, t4 = lane & 3;')
A('        int cols8 = p.Cols / 8;')
decl = f'.reg .f32 td<{NACC}>;' + ''.join(f'\\n\\tmov.f32 td{i}, 0f00000000;' for i in range(NACC))
A(f'        CudaAsm.Emit("{decl}");')
A('        // this thread\'s load slots: weight groups (row, 8-column offset) and activation groups (token, 8-column offset)')
for e in range(A_GROUPS):
    A(f'        int ar{e} = (tid + {e * THREADS}) >> 2, ak{e} = ((tid + {e * THREADS}) & 3) * 8;')
for e in range(B_GROUPS):
    A(f'        int bt{e} = (tid + {e * THREADS}) >> 2, bk{e} = ((tid + {e * THREADS}) & 3) * 8;')
# load helpers inline: produce Words4 for weights and activations
def load_step(kexpr, suffix):
    for e in range(A_GROUPS):
        A(f'        Words4 wa{e}{suffix} = default;')
        A(f'        if ({A_GUARD}row0 + ar{e} < p.Rows)')
        A('        {')
        A(f'            Float8 v = fmt.Dequant8(w, p.WWord + (long)(row0 + ar{e}) * p.RowWords, p.Cols, {kexpr} + ak{e});')
        A(f'            wa{e}{suffix}.A = Tc2Pack(v.W0, v.W1); wa{e}{suffix}.B = Tc2Pack(v.W2, v.W3); wa{e}{suffix}.C = Tc2Pack(v.W4, v.W5); wa{e}{suffix}.D = Tc2Pack(v.W6, v.W7);')
        A('        }')
    for e in range(B_GROUPS):
        A(f'        Words4 xb{e}{suffix} = {B_GUARD}tok0 + bt{e} < p.NTok ? x4[(long)(tok0 + bt{e}) * cols8 + ({kexpr} + bk{e}) / 8] : default;')
def store_step(buf, suffix, indent='        '):
    for e in range(A_GROUPS):
        A(f'{indent}{"if (tid < " + str(A_TOTAL) + ") " if A_GUARD else ""}a4[(({buf}) * {BM} + ar{e}) * ({LD} / 8) + ak{e} / 8] = wa{e}{suffix};')
    for e in range(B_GROUPS):
        A(f'{indent}{"if (tid < " + str(B_TOTAL) + ") " if B_GUARD else ""}b4[(({buf}) * {BN} + bt{e}) * ({LD} / 8) + bk{e} / 8] = xb{e}{suffix};')
A('        // prologue: step 0 into buffer 0')
load_step('0', '0')
store_step('0', '0')
A('        Group.Barrier();')
A(f'        for (int k0 = 0, buf = 0; k0 < p.Cols; k0 += {BK}, buf ^= 1)')
A('        {')
A(f'            bool more = k0 + {BK} < p.Cols;')
A(f'            int kn = more ? k0 + {BK} : k0;')
# next-step loads (always executed for uniform control flow; values unused on the last step)
for e in range(A_GROUPS):
    A(f'            Words4 wa{e}n = default;')
    A(f'            if ({A_GUARD}more && row0 + ar{e} < p.Rows)')
    A('            {')
    A(f'                Float8 v = fmt.Dequant8(w, p.WWord + (long)(row0 + ar{e}) * p.RowWords, p.Cols, kn + ak{e});')
    A(f'                wa{e}n.A = Tc2Pack(v.W0, v.W1); wa{e}n.B = Tc2Pack(v.W2, v.W3); wa{e}n.C = Tc2Pack(v.W4, v.W5); wa{e}n.D = Tc2Pack(v.W6, v.W7);')
    A('            }')
for e in range(B_GROUPS):
    A(f'            Words4 xb{e}n = {B_GUARD}more && tok0 + bt{e} < p.NTok ? x4[(long)(tok0 + bt{e}) * cols8 + (kn + bk{e}) / 8] : default;')
A(f'            int abase = buf * {BM} * ({LD} / 2), bbase = buf * {BN} * ({LD} / 2);')
A(f'            for (int ks = 0; ks < {BK}; ks += 16)')
A('            {')
A('                int ka = (ks + 2 * t4) / 2; // word offset of the k pair')
for mi in range(MT):
    A(f'                int ra{mi} = abase + (wr + {mi * 16} + g) * ({LD} / 2) + ka;')
    A(f'                uint fa{mi}_0 = a32[ra{mi}], fa{mi}_1 = a32[ra{mi} + 4 * {LD}], fa{mi}_2 = a32[ra{mi} + 4], fa{mi}_3 = a32[ra{mi} + 4 * {LD} + 4];')
for ni in range(NT):
    A(f'                int rb{ni} = bbase + (wc + {ni * 8} + g) * ({LD} / 2) + ka;')
    A(f'                uint fb{ni}_0 = b32[rb{ni}], fb{ni}_1 = b32[rb{ni} + 4];')
for mi in range(MT):
    for ni in range(NT):
        base = 4 * (mi * NT + ni)
        acc = ','.join(f'td{base + i}' for i in range(4))
        A(f'                CudaAsm.Emit("mma.sync.aligned.m16n8k16.row.col.f32.f16.f16.f32 {{{acc}}}, {{%0,%1,%2,%3}}, {{%4,%5}}, {{{acc}}};", fa{mi}_0, fa{mi}_1, fa{mi}_2, fa{mi}_3, fb{ni}_0, fb{ni}_1);')
A('            }')
A('            if (more)')
A('            {')
store_step('buf ^ 1', 'n', '                ')
A('            }')
A('            Group.Barrier();')
A('        }')
# epilogue
for mi in range(MT):
    for ni in range(NT):
        base = 4 * (mi * NT + ni)
        A('        {')
        for i in range(4):
            A(f'            CudaAsm.Emit("mov.f32 %0, td{base + i};", out float c{i});')
        A(f'            int r = row0 + wr + {mi * 16} + g, t = tok0 + wc + {ni * 8} + 2 * t4;')
        A('            TcStore(f, y, p, r, t, c0, c1);')
        A('            TcStore(f, y, p, r + 8, t, c2, c3);')
        A('        }')
A('    }')
A('')
A('    /// <summary>Two floats as an fp16x2 word (lo in the low half).</summary>')
A('    private static uint Tc2Pack(float lo, float hi)')
A('    {')
A('        CudaAsm.Emit("cvt.rn.f16x2.f32 %0, %1, %2;", out uint packed, hi, lo);')
A('        return packed;')
A('    }')
A('')
A('    /// <summary>')
A('    /// Activations for <see cref="TcGemm2{T}"/>: xh[t, c] = (half)clamp(x[XOff + t·XStride + c]), four columns per thread,')
A('    /// once per GEMM instead of once per weight-row block.')
A('    /// </summary>')
A('    public static void ToHalfRows(Index1D i, ArrayView<float> x, ArrayView<Half> xh, long xOff, int xStride, int cols)')
A('    {')
A('        int c4 = cols / 4, t = (int)(i / c4), c = (int)(i - (long)t * c4) * 4;')
A('        Float4 v = x.Cast<Float4>()[(xOff + (long)t * xStride + c) / 4];')
A('        var h2 = xh.Cast<uint>();')
A('        long o = ((long)t * cols + c) / 2;')
A('        h2[o] = Tc2Pack(Clamp16(v.X), Clamp16(v.Y));')
A('        h2[o + 1] = Tc2Pack(Clamp16(v.Z), Clamp16(v.W));')
A('    }')
A('}')
with open(OUT, 'w', newline='\n', encoding='utf-8') as fh:
    fh.write('\n'.join(L) + '\n')
print(f'wrote {OUT}: {len(L)} lines ({MT}x{NT} tiles per warp, {A_GROUPS}+{B_GROUPS} load groups per thread)')
