import os
import sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
# Generates the 64-query tensor-core attention kernel (FlashAttention-2 layout). Usage: python tensor_core_attention64.py [out.cs]
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'src', 'Lamma.Net.Gpu', 'TensorCoreAttention64.cs')
NOUT = 16  # 8-wide output tiles per warp: hd <= 128
NS = 4     # 8-wide score tiles per chunk: 32 keys

L = []
A = L.append
A('using ILGPU;')
A('using ILGPU.Runtime;')
A('using ILGPU.Runtime.Cuda;')
A('using Half = ILGPU.Half;')
A('')
A('namespace LammaNet.Gpu;')
A('')
A('// <auto-generated> by tools/gpu-codegen/tensor_core_attention64.py: PTX strings name fixed registers (score tiles')
A('// sc0-15, output tiles o0-o63), so every tile has its own literal statements.')
A('')
A('internal static partial class Kernels')
A('{')
A('    /// <summary>Query rows per block of <see cref="TcAttnPrefill64"/> (tiles must be built with this size).</summary>')
A('    public const int Fa2Q = 64;')
A('    /// <summary>Largest head dimension of <see cref="TcAttnPrefill64"/> (<see cref="TcAttnPrefill64Small"/>: ≤ 64, less shared memory).</summary>')
A('    public const int Fa2MaxHd = 128, Fa2SmallHd = 64;')
A('    private const int Fa2KV = 32, Fa2VLd = Fa2KV + 8;')
A('')
def kernel(name, maxhd, small):
    nout = maxhd // 8
    ld = str(maxhd + 8)  # padded shared row (halves)
    A('    /// <summary>')
    A('    /// Tensor-core flash attention with the FlashAttention-2 work split (sm_80+): a 128-thread block handles one head for')
    A('    /// a tile of up to 64 consecutive query tokens of one sequence, warp w owning query rows 16w..16w+15 with all head')
    A('    /// dims. Per chunk of 32 key positions the block stages K (row-major) and V (transposed) in shared memory once for')
    A('    /// all 64 queries; each warp computes its 16x32 scores with mma, runs the online softmax in registers (quad')
    A('    /// shuffles), turns the score accumulators directly into the fp16 A operand of P·V and accumulates its 16 x hd output')
    A('    /// tile in registers. Per-row key ranges (tokInfo) give causal, sliding-window or full masks. hd is a JIT constant')
    A(f'    /// (multiple of 16, ≤ {maxhd}, == HdV). Grid: tiles × NHead.')
    A('    /// </summary>')
    A(f'    public static void {name}(ArrayView<float> q, ArrayView<Half> kc, ArrayView<Half> vc, ArrayView<int> pages, ArrayView<int> tokInfo,')
    A('        ArrayView<int> tiles, ArrayView<float> outp, AttnParams p, SpecializedValue<int> hdSpec)')
    A('    {')
    A('        int hd = hdSpec.Value, nOut = hd / 8;')
    A(f'        var qs = SharedMemory.Allocate<Half>(Fa2Q * {ld});')
    A(f'        var ks = SharedMemory.Allocate<Half>(Fa2KV * {ld});')
    A(f'        var vt = SharedMemory.Allocate<Half>({maxhd} * Fa2VLd);')
    A('        var slots = SharedMemory.Allocate<long>(Fa2KV);')
    A('        var q32 = qs.Cast<uint>();')
    A('        var k32 = ks.Cast<uint>();')
    A('        var ks8 = ks.Cast<Half8>();')
    A('        var v32 = vt.Cast<uint>();')
    A('        var k8 = kc.Cast<Half8>();')
    A('        var v8 = vc.Cast<Half8>();')
    A('        int tid = Group.IdxX, lane = tid & 31, warp = tid >> 5, g = lane >> 2, t4 = lane & 3;')
    A('        int tile = Grid.IdxX / p.NHead, h = Grid.IdxX % p.NHead;')
    A('        int t0 = tiles[2 * tile], cnt = tiles[2 * tile + 1];')
    A('        int kvh = h / (p.NHead / p.NKv);')
    A('        for (int e = tid; e < Fa2Q * hd; e += 128)')
    A('        {')
    A('            int r = e / hd, d = e - r * hd;')
    A(f'            qs[r * {ld} + d] = (Half)(r < cnt ? q[p.QOff + (long)(t0 + r) * p.QStride + (long)h * p.QHeadPitch + d] * p.Scale : 0f);')
    A('        }')
    A('        // this thread\'s two query rows (g and g + 8 of its warp) and their key ranges; rows past the tile get empty ranges')
    A('        int rowA = 16 * warp + g, rowB = rowA + 8;')
    A('        int begA = 1, endA = 0, begB = 1, endB = 0;')
    A('        if (rowA < cnt) { begA = tokInfo[3 * (t0 + rowA) + 1]; endA = tokInfo[3 * (t0 + rowA) + 2]; }')
    A('        if (rowB < cnt) { begB = tokInfo[3 * (t0 + rowB) + 1]; endB = tokInfo[3 * (t0 + rowB) + 2]; }')
    A('        float mA = float.NegativeInfinity, mB = float.NegativeInfinity, lA = 0f, lB = 0f;')
    A('        int pt = tokInfo[3 * t0];')
    A('        int kLo = tokInfo[3 * t0 + 1], kHi = tokInfo[3 * (t0 + cnt - 1) + 2];')
    o_decl = f'.reg .f32 o<{4 * nout}>;' + ''.join(f'\\n\\tmov.f32 o{i}, 0f00000000;' for i in range(4 * nout)) + f'\\n\\t.reg .f32 sc<{4 * NS}>;'
    A(f'        CudaAsm.Emit("{o_decl}");')
    A('        for (int c0 = kLo; c0 <= kHi; c0 += Fa2KV)')
    A('        {')
    A('            Group.Barrier();')
    A('            if (tid < Fa2KV)')
    A('            {')
    A('                int pos = c0 + tid;')
    A('                slots[tid] = pos <= kHi ? (long)pages[pt + pos / p.PageSize] * p.PageSize + pos % p.PageSize : -1;')
    A('            }')
    A('            Group.Barrier();')
    A('            // K rows (position-major, 16-byte vectors)')
    A('            for (int e = tid; e < Fa2KV * hd / 8; e += 128)')
    A('            {')
    A('                int pp = e / (hd / 8), d8 = e - pp * (hd / 8);')
    A('                long sl = slots[pp];')
    A(f'                ks8[pp * ({ld} / 8) + d8] = sl >= 0 ? k8[(sl * p.KRow + (long)kvh * p.Hd) / 8 + d8] : default;')
    A('            }')
    A('            // V transposed (dim-major): consecutive threads take consecutive positions, so the stores do not conflict')
    A('            for (int e = tid; e < Fa2KV * hd / 8; e += 128)')
    A('            {')
    A('                int d8 = e / Fa2KV, pp = e - d8 * Fa2KV;')
    A('                long sl = slots[pp];')
    A('                Half8 hv = sl >= 0 ? v8[(sl * p.VRow + (long)kvh * p.HdV) / 8 + d8] : default;')
    A('                int vb = d8 * 8 * Fa2VLd + pp;')
    A('                vt[vb] = hv.H0; vt[vb + Fa2VLd] = hv.H1; vt[vb + 2 * Fa2VLd] = hv.H2; vt[vb + 3 * Fa2VLd] = hv.H3;')
    A('                vt[vb + 4 * Fa2VLd] = hv.H4; vt[vb + 5 * Fa2VLd] = hv.H5; vt[vb + 6 * Fa2VLd] = hv.H6; vt[vb + 7 * Fa2VLd] = hv.H7;')
    A('            }')
    A('            Group.Barrier();')
    A('            // scores S = Q·Kᵀ for this warp\'s 16 rows and the 32 positions: 4 tiles of 8 positions')
    zero_sc = '\\n\\t'.join(f'mov.f32 sc{i}, 0f00000000;' for i in range(4 * NS))
    A(f'            CudaAsm.Emit("{zero_sc}");')
    A('            for (int kd = 0; kd < hd; kd += 16)')
    A('            {')
    A(f'                int qa = rowA * ({ld} / 2) + (kd + 2 * t4) / 2;')
    A(f'                uint a0 = q32[qa], a1 = q32[qa + 4 * {ld}], a2 = q32[qa + 4], a3 = q32[qa + 4 * {ld} + 4];')
    for j in range(NS):
        r = ','.join(f'sc{4 * j + i}' for i in range(4))
        A('                {')
        A(f'                    int kb = ({8 * j} + g) * ({ld} / 2) + (kd + 2 * t4) / 2;')
        A(f'                    CudaAsm.Emit("mma.sync.aligned.m16n8k16.row.col.f32.f16.f16.f32 {{{r}}}, {{%0,%1,%2,%3}}, {{%4,%5}}, {{{r}}};", a0, a1, a2, a3, k32[kb], k32[kb + 4]);')
        A('                }')
    A('            }')
    for i in range(4 * NS):
        A(f'            CudaAsm.Emit("mov.f32 %0, sc{i};", out float s{i});')
    A('            // masks (per-row key range) and soft-capping; tile j holds (row A: s[4j], s[4j+1]; row B: s[4j+2], s[4j+3]) at')
    A('            // positions c0 + 8j + 2·t4 and + 1')
    for j in range(NS):
        A(f'            int pc{j} = c0 + {8 * j} + 2 * t4;')
        A(f'            s{4*j} = Fa2Mask(s{4*j}, pc{j}, begA, endA, p.SoftCap); s{4*j+1} = Fa2Mask(s{4*j+1}, pc{j} + 1, begA, endA, p.SoftCap);')
        A(f'            s{4*j+2} = Fa2Mask(s{4*j+2}, pc{j}, begB, endB, p.SoftCap); s{4*j+3} = Fa2Mask(s{4*j+3}, pc{j} + 1, begB, endB, p.SoftCap);')
    rowa = [4 * j + i for j in range(NS) for i in (0, 1)]
    rowb = [4 * j + i for j in range(NS) for i in (2, 3)]
    def maxexpr(idx):
        e = [f's{i}' for i in idx]
        while len(e) > 1:
            e = [f'MathF.Max({e[k]}, {e[k + 1]})' for k in range(0, len(e), 2)]
        return e[0]
    A(f'            float xA = {maxexpr(rowa)};')
    A(f'            float xB = {maxexpr(rowb)};')
    A('            xA = MathF.Max(xA, ILGPU.Warp.ShuffleXor(xA, 1));')
    A('            xA = MathF.Max(xA, ILGPU.Warp.ShuffleXor(xA, 2));')
    A('            xB = MathF.Max(xB, ILGPU.Warp.ShuffleXor(xB, 1));')
    A('            xB = MathF.Max(xB, ILGPU.Warp.ShuffleXor(xB, 2));')
    A('            float nA = MathF.Max(mA, xA), nB = MathF.Max(mB, xB);')
    A('            // a row with no visible position yet keeps a -inf max: nothing to add, nothing to rescale')
    A('            bool liveA = nA > float.NegativeInfinity, liveB = nB > float.NegativeInfinity;')
    A('            float cA = liveA ? MathF.Exp(mA - nA) : 1f, cB = liveB ? MathF.Exp(mB - nB) : 1f;')
    for i in rowa:
        A(f'            float p{i} = liveA ? MathF.Exp(s{i} - nA) : 0f;')
    for i in rowb:
        A(f'            float p{i} = liveB ? MathF.Exp(s{i} - nB) : 0f;')
    A('            float sumA = ' + ' + '.join(f'p{i}' for i in rowa) + ';')
    A('            float sumB = ' + ' + '.join(f'p{i}' for i in rowb) + ';')
    A('            sumA += ILGPU.Warp.ShuffleXor(sumA, 1);')
    A('            sumA += ILGPU.Warp.ShuffleXor(sumA, 2);')
    A('            sumB += ILGPU.Warp.ShuffleXor(sumB, 1);')
    A('            sumB += ILGPU.Warp.ShuffleXor(sumB, 2);')
    A('            lA = lA * cA + sumA; mA = nA;')
    A('            lB = lB * cB + sumB; mB = nB;')
    for n in range(nout):
        A(f'            if (nOut > {n}) CudaAsm.Emit("mul.f32 o{4*n}, o{4*n}, %0;\\n\\tmul.f32 o{4*n+1}, o{4*n+1}, %0;\\n\\tmul.f32 o{4*n+2}, o{4*n+2}, %1;\\n\\tmul.f32 o{4*n+3}, o{4*n+3}, %1;", cA, cB);')
    A('            // O += P·V: the score tiles 2s and 2s+1 are exactly the A fragment of k-step s (positions 16s..16s+15)')
    for s in range(NS // 2):
        j0, j1 = 2 * s, 2 * s + 1
        A(f'            {{')
        A(f'                uint a0 = Fa2Pack(p{4*j0}, p{4*j0+1}), a1 = Fa2Pack(p{4*j0+2}, p{4*j0+3}), a2 = Fa2Pack(p{4*j1}, p{4*j1+1}), a3 = Fa2Pack(p{4*j1+2}, p{4*j1+3});')
        for n in range(nout):
            r = ','.join(f'o{4 * n + i}' for i in range(4))
            A(f'                if (nOut > {n})')
            A(f'                {{')
            A(f'                    int vb = ({8 * n} + g) * (Fa2VLd / 2) + ({16 * s} + 2 * t4) / 2;')
            A(f'                    CudaAsm.Emit("mma.sync.aligned.m16n8k16.row.col.f32.f16.f16.f32 {{{r}}}, {{%0,%1,%2,%3}}, {{%4,%5}}, {{{r}}};", a0, a1, a2, a3, v32[vb], v32[vb + 4]);')
            A(f'                }}')
        A(f'            }}')
    A('        }')
    A('        float iA = lA > 0 ? 1f / lA : 0f, iB = lB > 0 ? 1f / lB : 0f;')
    for n in range(nout):
        A(f'        if (nOut > {n})')
        A('        {')
        for i in range(4):
            A(f'            CudaAsm.Emit("mov.f32 %0, o{4*n+i};", out float v{i});')
        A(f'            TaStore(q, outp, p, t0, cnt, h, rowA, {8 * n} + 2 * t4, v0 * iA, v1 * iA);')
        A(f'            TaStore(q, outp, p, t0, cnt, h, rowB, {8 * n} + 2 * t4, v2 * iB, v3 * iB);')
        A('        }')
    A('    }')
    A('')


kernel('TcAttnPrefill64', 128, False)
A('')
kernel('TcAttnPrefill64Small', 64, True)
A('')
A('    private static float Fa2Mask(float s, int pos, int start, int end, float softCap)')
A('    {')
A('        if (pos < start || pos > end) return float.NegativeInfinity;')
A('        return softCap > 0 ? Tanh(s / softCap) * softCap : s;')
A('    }')
A('')
A('    /// <summary>Two floats as an fp16x2 register (lo in the low half), the A-operand element order of mma.</summary>')
A('    private static uint Fa2Pack(float lo, float hi)')
A('    {')
A('        CudaAsm.Emit("cvt.rn.f16x2.f32 %0, %1, %2;", out uint packed, hi, lo);')
A('        return packed;')
A('    }')
A('}')
with open(OUT, 'w', newline='\n', encoding='utf-8') as fh:
    fh.write('\n'.join(L) + '\n')
print(f'wrote {OUT}: {len(L)} lines')
