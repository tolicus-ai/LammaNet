import os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
# Generates the tensor-core prefill attention kernel.
L = []
A = L.append
A('using ILGPU;')
A('using ILGPU.Runtime;')
A('using ILGPU.Runtime.Cuda;')
A('using Half = ILGPU.Half;')
A('')
A('namespace LammaNet.Gpu;')
A('')
A('// <auto-generated> by tools/gpu-codegen/tensor_core_attention.py: PTX strings name fixed registers (score tile sc0-3,')
A('// output tiles o0-o31), so every tile has its own literal statements.')
A('')
A('internal static partial class Kernels')
A('{')
A('    private const int TaQ = 16, TaKV = 32, TaMaxHd = 256, TaQLd = TaMaxHd + 8, TaKLd = TaMaxHd + 8, TaVLd = TaKV + 8, TaPLd = TaKV + 8;')
A('')
A('    /// <summary>')
A('    /// Tensor-core flash attention for prompt batches (sm_80+). A 128-thread block handles one head for a tile of up to')
A('    /// 16 consecutive query tokens of one sequence. Per chunk of 32 key positions: warp w computes the 16x8 score tile')
A('    /// of positions 8w..8w+7 with mma (fp16 Q, K), the block runs an online softmax over the 16x32 scores, and warp w')
A('    /// accumulates P·V for head dims [w·hd/4, (w+1)·hd/4) into registers that persist across chunks. hd is a JIT')
A('    /// constant (multiple of 32, ≤ 256, == HdV). Grid: tiles × NHead.')
A('    /// </summary>')
A('    public static void TcAttnPrefill(ArrayView<float> q, ArrayView<Half> kc, ArrayView<Half> vc, ArrayView<int> pages, ArrayView<int> tokInfo,')
A('        ArrayView<int> tiles, ArrayView<float> outp, AttnParams p, SpecializedValue<int> hdSpec) =>')
A('        TcAttnPrefillCore(q, kc, vc, pages, tokInfo, tiles, outp, p, hdSpec, 0);')
A('')
A('    internal static void TcAttnPrefillQ8(ArrayView<float> q, ArrayView<Half> kc, ArrayView<Half> vc, ArrayView<int> pages, ArrayView<int> tokInfo,')
A('        ArrayView<int> tiles, ArrayView<float> outp, AttnParams p, SpecializedValue<int> hdSpec) =>')
A('        TcAttnPrefillCore(q, kc, vc, pages, tokInfo, tiles, outp, p, hdSpec, 1);')
A('')
A('    private static void TcAttnPrefillCore(ArrayView<float> q, ArrayView<Half> kc, ArrayView<Half> vc, ArrayView<int> pages, ArrayView<int> tokInfo,')
A('        ArrayView<int> tiles, ArrayView<float> outp, AttnParams p, SpecializedValue<int> hdSpec, int compact)')
A('    {')
A('        int hd = hdSpec.Value;')
A('        var qs = SharedMemory.Allocate<Half>(TaQ * TaQLd);')
A('        var kvb = SharedMemory.Allocate<Half>(TaMaxHd * TaVLd > TaKV * TaKLd ? TaMaxHd * TaVLd : TaKV * TaKLd);')
A('        var ps = SharedMemory.Allocate<Half>(TaQ * TaPLd);')
A('        var sm = SharedMemory.Allocate<float>(TaQ * TaKV);')
A('        var rowM = SharedMemory.Allocate<float>(TaQ);')
A('        var rowL = SharedMemory.Allocate<float>(TaQ);')
A('        var rowC = SharedMemory.Allocate<float>(TaQ);')
A('        var slots = SharedMemory.Allocate<long>(TaKV);')
A('        var q32 = qs.Cast<uint>();')
A('        var kv32 = kvb.Cast<uint>();')
A('        var kv8 = kvb.Cast<Half8>();')
A('        var p32 = ps.Cast<uint>();')
A('        int tid = Group.IdxX, lane = tid & 31, warp = tid >> 5, g = lane >> 2, t4 = lane & 3;')
A('        int tile = Grid.IdxX / p.NHead, h = Grid.IdxX % p.NHead;')
A('        int t0 = tiles[2 * tile], cnt = tiles[2 * tile + 1];')
A('        int kvh = h / (p.NHead / p.NKv);')
A('        int nTiles = hd / 32; // 8-wide output tiles per warp')
A('        for (int e = tid; e < TaQ * hd; e += 128)')
A('        {')
A('            int r = e / hd, d = e % hd;')
A('            qs[r * TaQLd + d] = (Half)(r < cnt ? q[p.QOff + (long)(t0 + r) * p.QStride + (long)h * p.QHeadPitch + d] * p.Scale : 0f);')
A('        }')
A('        if (tid < TaQ) { rowM[tid] = float.NegativeInfinity; rowL[tid] = 0f; }')
A('        int pt = tokInfo[3 * t0];')
A('        int kLo = tokInfo[3 * t0 + 1], kHi = tokInfo[3 * (t0 + cnt - 1) + 2];')
o_decl = '.reg .f32 o<32>;' + ''.join(f'\\n\\tmov.f32 o{i}, 0f00000000;' for i in range(32)) + '\\n\\t.reg .f32 sc<4>;'
A(f'        CudaAsm.Emit("{o_decl}");')
A('        for (int c0 = kLo; c0 <= kHi; c0 += TaKV)')
A('        {')
A('            Group.Barrier();')
A('            if (tid < TaKV)')
A('            {')
A('                int pos = c0 + tid;')
A('                slots[tid] = pos <= kHi ? (long)pages[pt + pos / p.PageSize] * p.PageSize + pos % p.PageSize : -1;')
A('            }')
A('            Group.Barrier();')
A('            for (int e = tid; e < TaKV * hd / 8; e += 128)')
A('            {')
A('                int pp = e / (hd / 8), d8 = e % (hd / 8);')
A('                long sl = slots[pp];')
A('                kv8[pp * (TaKLd / 8) + d8] = sl >= 0 ? LoadCache8(kc, (sl * p.KRow + (long)kvh * p.Hd) / 8 + d8, compact) : default;')
A('            }')
A('            Group.Barrier();')
A('            // scores of positions 8w..8w+7: A = Q (rows g, g+8), B = K rows (n = position)')
A('            CudaAsm.Emit("mov.f32 sc0, 0f00000000;\\n\\tmov.f32 sc1, 0f00000000;\\n\\tmov.f32 sc2, 0f00000000;\\n\\tmov.f32 sc3, 0f00000000;");')
A('            for (int kd = 0; kd < hd; kd += 16)')
A('            {')
A('                int qa = g * (TaQLd / 2) + (kd + 2 * t4) / 2;')
A('                uint a0 = q32[qa], a1 = q32[qa + 4 * TaQLd], a2 = q32[qa + 4], a3 = q32[qa + 4 * TaQLd + 4];')
A('                int kb = (8 * warp + g) * (TaKLd / 2) + (kd + 2 * t4) / 2;')
A('                uint b0 = kv32[kb], b1 = kv32[kb + 4];')
A('                CudaAsm.Emit("mma.sync.aligned.m16n8k16.row.col.f32.f16.f16.f32 {sc0,sc1,sc2,sc3}, {%0,%1,%2,%3}, {%4,%5}, {sc0,sc1,sc2,sc3};", a0, a1, a2, a3, b0, b1);')
A('            }')
A('            CudaAsm.Emit("mov.f32 %0, sc0;", out float s00);')
A('            CudaAsm.Emit("mov.f32 %0, sc1;", out float s01);')
A('            CudaAsm.Emit("mov.f32 %0, sc2;", out float s10);')
A('            CudaAsm.Emit("mov.f32 %0, sc3;", out float s11);')
A('            int pc = 8 * warp + 2 * t4;')
A('            sm[g * TaKV + pc] = TaMask(s00, g, c0 + pc, t0, cnt, tokInfo, p.SoftCap);')
A('            sm[g * TaKV + pc + 1] = TaMask(s01, g, c0 + pc + 1, t0, cnt, tokInfo, p.SoftCap);')
A('            sm[(g + 8) * TaKV + pc] = TaMask(s10, g + 8, c0 + pc, t0, cnt, tokInfo, p.SoftCap);')
A('            sm[(g + 8) * TaKV + pc + 1] = TaMask(s11, g + 8, c0 + pc + 1, t0, cnt, tokInfo, p.SoftCap);')
A('            Group.Barrier();')
A('            // online softmax: 8 threads per row, 4 positions each')
A('            {')
A('                int r = tid >> 3, j = tid & 7;')
A('                float x0 = sm[r * TaKV + 4 * j], x1 = sm[r * TaKV + 4 * j + 1], x2 = sm[r * TaKV + 4 * j + 2], x3 = sm[r * TaKV + 4 * j + 3];')
A('                float mx = MathF.Max(MathF.Max(x0, x1), MathF.Max(x2, x3));')
A('                mx = MathF.Max(mx, ILGPU.Warp.ShuffleXor(mx, 1));')
A('                mx = MathF.Max(mx, ILGPU.Warp.ShuffleXor(mx, 2));')
A('                mx = MathF.Max(mx, ILGPU.Warp.ShuffleXor(mx, 4));')
A('                float mOld = rowM[r], mNew = MathF.Max(mOld, mx);')
A('                float corr = 1f, e0 = 0, e1 = 0, e2 = 0, e3 = 0;')
A('                if (mNew > float.NegativeInfinity)')
A('                {')
A('                    corr = MathF.Exp(mOld - mNew);')
A('                    e0 = MathF.Exp(x0 - mNew); e1 = MathF.Exp(x1 - mNew); e2 = MathF.Exp(x2 - mNew); e3 = MathF.Exp(x3 - mNew);')
A('                }')
A('                float rs = e0 + e1 + e2 + e3;')
A('                rs += ILGPU.Warp.ShuffleXor(rs, 1);')
A('                rs += ILGPU.Warp.ShuffleXor(rs, 2);')
A('                rs += ILGPU.Warp.ShuffleXor(rs, 4);')
A('                int pb = r * TaPLd + 4 * j;')
A('                ps[pb] = (Half)e0; ps[pb + 1] = (Half)e1; ps[pb + 2] = (Half)e2; ps[pb + 3] = (Half)e3;')
A('                ILGPU.Warp.Barrier();')
A('                if (j == 0) { rowM[r] = mNew; rowL[r] = rowL[r] * corr + rs; rowC[r] = corr; }')
A('            }')
A('            Group.Barrier();')
A('            // V chunk transposed: Vt[dim][pos]; consecutive threads take consecutive positions so the scalar stores do not conflict')
A('            for (int e = tid; e < TaKV * hd / 8; e += 128)')
A('            {')
A('                int d8 = e / TaKV, pp = e % TaKV;')
A('                long sl = slots[pp];')
A('                Half8 hv = sl >= 0 ? LoadCache8(vc, (sl * p.VRow + (long)kvh * p.HdV) / 8 + d8, compact) : default;')
A('                int d = d8 * 8;')
A('                kvb[(d + 0) * TaVLd + pp] = hv.H0; kvb[(d + 1) * TaVLd + pp] = hv.H1; kvb[(d + 2) * TaVLd + pp] = hv.H2; kvb[(d + 3) * TaVLd + pp] = hv.H3;')
A('                kvb[(d + 4) * TaVLd + pp] = hv.H4; kvb[(d + 5) * TaVLd + pp] = hv.H5; kvb[(d + 6) * TaVLd + pp] = hv.H6; kvb[(d + 7) * TaVLd + pp] = hv.H7;')
A('            }')
A('            Group.Barrier();')
A('            float cg = rowC[g], cg8 = rowC[g + 8];')
for i in range(8):
    regs = [f'o{4*i+k}' for k in range(4)]
    A(f'            if (nTiles > {i}) CudaAsm.Emit("mul.f32 {regs[0]}, {regs[0]}, %0;\\n\\tmul.f32 {regs[1]}, {regs[1]}, %0;\\n\\tmul.f32 {regs[2]}, {regs[2]}, %1;\\n\\tmul.f32 {regs[3]}, {regs[3]}, %1;", cg, cg8);')
A('            for (int kp = 0; kp < TaKV; kp += 16)')
A('            {')
A('                int pa = g * (TaPLd / 2) + (kp + 2 * t4) / 2;')
A('                uint a0 = p32[pa], a1 = p32[pa + 4 * TaPLd], a2 = p32[pa + 4], a3 = p32[pa + 4 * TaPLd + 4];')
A('                int dBase = warp * (hd / 4);')
for i in range(8):
    regs = ','.join(f'o{4*i+k}' for k in range(4))
    A(f'                if (nTiles > {i})')
    A('                {')
    A(f'                    int vb = (dBase + {8*i} + g) * (TaVLd / 2) + (kp + 2 * t4) / 2;')
    A(f'                    CudaAsm.Emit("mma.sync.aligned.m16n8k16.row.col.f32.f16.f16.f32 {{{regs}}}, {{%0,%1,%2,%3}}, {{%4,%5}}, {{{regs}}};", a0, a1, a2, a3, kv32[vb], kv32[vb + 4]);')
    A('                }')
A('            }')
A('        }')
A('        Group.Barrier();')
A('        float ig = rowL[g] > 0 ? 1f / rowL[g] : 0f, ig8 = rowL[g + 8] > 0 ? 1f / rowL[g + 8] : 0f;')
A('        int d0 = warp * (hd / 4) + 2 * t4;')
for i in range(8):
    A(f'        if (nTiles > {i})')
    A('        {')
    for k in range(4):
        A(f'            CudaAsm.Emit("mov.f32 %0, o{4*i+k};", out float v{k});')
    A(f'            TaStore(q, outp, p, t0, cnt, h, g, d0 + {8*i}, v0 * ig, v1 * ig);')
    A(f'            TaStore(q, outp, p, t0, cnt, h, g + 8, d0 + {8*i}, v2 * ig8, v3 * ig8);')
    A('        }')
A('    }')
A('')
A('    private static float TaMask(float s, int r, int pos, int t0, int cnt, ArrayView<int> tokInfo, float softCap)')
A('    {')
A('        if (r >= cnt) return float.NegativeInfinity;')
A('        int start = tokInfo[3 * (t0 + r) + 1], end = tokInfo[3 * (t0 + r) + 2];')
A('        if (pos < start || pos > end) return float.NegativeInfinity;')
A('        return softCap > 0 ? Tanh(s / softCap) * softCap : s;')
A('    }')
A('')
A('    private static void TaStore(ArrayView<float> q, ArrayView<float> outp, AttnParams p, int t0, int cnt, int h, int r, int d, float v0, float v1)')
A('    {')
A('        if (r >= cnt) return;')
A('        long oo = p.OutOff + (long)(t0 + r) * p.OutStride + (long)h * p.HdV + d;')
A('        if (p.Gated != 0)')
A('        {')
A('            long go = p.QOff + (long)(t0 + r) * p.QStride + (long)h * p.QHeadPitch + p.Hd + d;')
A('            v0 *= Sigmoid(q[go]); v1 *= Sigmoid(q[go + 1]);')
A('        }')
A('        outp[oo] = v0;')
A('        outp[oo + 1] = v1;')
A('    }')
A('}')
